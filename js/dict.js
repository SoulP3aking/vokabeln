/* ═══════════════════════════════════════════════════════
   Nachschlagen
   ═══════════════════════════════════════════════════════ */

const Dict = (() => {
  /* Spalte je Sprachcode */
  const COL = { de: 0, en: 1, es: 2, fr: 3 };

  /* Artikel abschneiden, damit "das Haus" auch bei "Haus" gefunden wird */
  const ART = /^(der|die|das|den|dem|el|la|los|las|le|les|un|una|une|the|an|a)\s+/i;
  const ELIDED = /^l['’]/i;

  const stripArticle = s => s.replace(ART, '').replace(ELIDED, '');

  /** Kleinschreibung ohne Akzente – damit "cafe" auch "café" findet. */
  const norm = s => String(s)
    .toLowerCase()
    .normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/ß/g, 'ss')
    .replace(/[^a-z0-9'’ ]/g, ' ')
    .trim().replace(/\s+/g, ' ');

  /* Suchschlüssel einmalig vorberechnen */
  const KEYS = DICT.map(row => row.map(w => norm(stripArticle(w))));

  const supports = code => Object.prototype.hasOwnProperty.call(COL, code);

  /**
   * Sucht Wörter, die zur Eingabe passen.
   * Treffer am Wortanfang stehen vor Treffern mitten im Wort.
   * @returns [{from, to, row}]
   */
  function lookup(query, fromCode, toCode, limit = 6) {
    if (!supports(fromCode) || !supports(toCode) || fromCode === toCode) return [];
    const q = norm(stripArticle(query));
    if (q.length < 2) return [];

    const from = COL[fromCode], to = COL[toCode];
    const starts = [], contains = [];

    for (let i = 0; i < KEYS.length; i++) {
      const key = KEYS[i][from];
      if (key === q) starts.unshift(i);           // exakter Treffer ganz nach vorne
      else if (key.startsWith(q)) starts.push(i);
      else if (key.includes(q)) contains.push(i);
      if (starts.length >= limit) break;
    }

    return [...starts, ...contains].slice(0, limit).map(i => ({
      from: DICT[i][from],
      to: DICT[i][to],
      row: DICT[i]
    }));
  }

  /** Alle vier Sprachen zu einer Eingabe – für die Nachschlagen-Ansicht. */
  function lookupAll(query, limit = 12) {
    const q = norm(stripArticle(query));
    if (q.length < 2) return [];
    const starts = [], contains = [];

    for (let i = 0; i < KEYS.length; i++) {
      const keys = KEYS[i];
      if (keys.some(k => k === q || k.startsWith(q))) starts.push(i);
      else if (keys.some(k => k.includes(q))) contains.push(i);
    }
    return [...starts, ...contains].slice(0, limit).map(i => DICT[i]);
  }

  return { lookup, lookupAll, supports, norm, stripArticle, size: DICT.length, COL };
})();
